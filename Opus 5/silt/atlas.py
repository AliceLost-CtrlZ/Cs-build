def _markdown_to_html(markdown: str) -> str:
    """Enough Markdown for the gazetteer: headings, tables, lists, bold, italic."""
    html = []
    rows = []

    def flush_table():
        if not rows:
            return
        header, *body = rows
        if body and set(body[0].replace("|", "").strip()) <= set("-: "):
            body = body[1:]
        html.append('<div class="wrap"><table>')
        cells = [c.strip() for c in header.strip("|").split("|")]
        html.append("<tr>" + "".join(f"<th>{c}</th>" for c in cells) + "</tr>")
        for line in body:
            cells = [c.strip() for c in line.strip("|").split("|")]
            html.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
        html.append("</table></div>")
        rows.clear()

    def inline(text: str) -> str:
        text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
        text = re.sub(r"\*(.+?)\*", r"<em>\1</em>", text)
        text = re.sub(r"`(.+?)`", r"<code>\1</code>", text)
        return text

    in_list = False
    for line in markdown.splitlines():
        stripped = line.strip()
        if stripped.startswith("|"):
            if in_list:
                html.append("</ul>")
                in_list = False
            rows.append(stripped)
            continue
        flush_table()

        if not stripped:
            if in_list:
                html.append("</ul>")
                in_list = False
            continue
        if stripped.startswith("- "):
            if not in_list:
                html.append("<ul>")
                in_list = True
            html.append(f"<li>{inline(stripped[2:])}</li>")
            continue
        if in_list:
            html.append("</ul>")
            in_list = False
        if stripped.startswith("## "):
            html.append(f"<h2>{inline(stripped[3:])}</h2>")
        elif stripped.startswith("# "):
            html.append(f"<h1>{inline(stripped[2:])}</h1>")
        else:
            classes = ' class="lede"' if stripped.startswith("*") else ""
            html.append(f"<p{classes}>{inline(stripped)}</p>")
    if in_list:
        html.append("</ul>")
    flush_table()
    return "\n".join(html)


def atlas_html(world, svg: str, markdown: str) -> str:
    """One page: the plate, then the gazetteer under it."""
    # Drop the XML-level width/height so the plate scales with the page.
    inline_svg = re.sub(
        r'(<svg\b[^>]*?)\s+width="[\d.]+"\s+height="[\d.]+"', r"\1", svg, count=1
    )
    body = _markdown_to_html(markdown)
    # The <h1> already appears inside the gazetteer; keep the browser tab honest.
    return _HTML_TEMPLATE.format(
        title=world.title.replace("<", "&lt;"), svg=inline_svg, body=body
    )


# -- writing --------------------------------------------------------------

FORMATS = ("svg", "png", "md", "json", "html")


def render_atlas(
    world,
    directory: str = ".",
    scale: int = 4,
    formats=FORMATS,
    basename: str | None = None,
    **draw_options,
):
    """Write the requested formats; returns ``{format: path}``."""
    formats = tuple(formats)
    unknown = set(formats) - set(FORMATS)
    if unknown:
        raise ValueError(f"unknown format(s): {', '.join(sorted(unknown))}")

    os.makedirs(directory, exist_ok=True)
    stem = basename or _slug(f"{world.name}-{world.seed}")
    written = {}

    svg = None
    if {"svg", "html"} & set(formats):
        svg = draw(world, scale=scale, **draw_options)

    markdown = None
    if {"md", "html"} & set(formats):
        markdown = gazetteer(world)

    if "svg" in formats:
        path = os.path.join(directory, f"{stem}.svg")
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(svg)
        written["svg"] = path

    if "png" in formats:
        path = os.path.join(directory, f"{stem}.png")
        rw, rh, pixels = raster(world, scale)
        png_mod.write(path, rw, rh, pixels)
        written["png"] = path

    if "md" in formats:
        path = os.path.join(directory, f"{stem}.md")
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(markdown)
        written["md"] = path

    if "json" in formats:
        path = os.path.join(directory, f"{stem}.json")
        with open(path, "w", encoding="utf-8") as handle:
            json.dump(world.summary(), handle, indent=2)
            handle.write("\n")
        written["json"] = path

    if "html" in formats:
        path = os.path.join(directory, f"{stem}.html")
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(atlas_html(world, svg, markdown))
        written["html"] = path

    return written
