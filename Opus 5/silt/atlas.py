"""Assembling the plate and its gazetteer.

A map is half the artefact. The other half is the index: the list at the back
that tells you the Tarkecrag range runs across the north-east, that its highest
point is 5,723 metres, and that the people who named it also named everything
within two hundred kilometres and nothing beyond.

This module turns a :class:`~silt.world.World` into files:

``<name>.svg``   the plate, self-contained, raster embedded
``<name>.png``   the ground raster on its own
``<name>.md``    the gazetteer, as prose and tables
``<name>.json``  every measurement, for anyone who wants to do their own thing
``<name>.html``  plate and gazetteer on one page, ready to open in a browser
"""

from __future__ import annotations

import json
import os
import re

from . import png as png_mod
from .climate import BIOMES
from .render import draw, raster
from .util import plural


def _slug(text: str) -> str:
    cleaned = re.sub(r"[^a-z0-9]+", "-", str(text).lower()).strip("-")
    return cleaned or "world"


def _bearing(world, x: float, y: float) -> str:
    return world.namer.compass_word(x, y)


def _cell_bearing(world, index: int) -> str:
    return _bearing(world, index % world.width, index // world.width)


# -- gazetteer ------------------------------------------------------------


def gazetteer(world) -> str:
    """The written half of the atlas, as Markdown."""
    features = world.features
    climate = world.climate
    lines = []
    add = lines.append

    lat_lo = climate.latitude(world.height_cells - 1)
    lat_hi = climate.latitude(0)
    lat_lo, lat_hi = min(lat_lo, lat_hi), max(lat_lo, lat_hi)

    add(f"# {world.title}")
    add("")
    add(f"*Seed `{world.seed}` · generated by Silt*")
    add("")

    shape_prose = {
        "continent": "a single landmass",
        "archipelago": "a scattering of islands",
        "peninsulas": "a ragged, deeply indented coast",
        "inland sea": "a ring of land around an enclosed sea",
    }.get(world.shape, world.shape)

    biomes = climate.biome_fractions(world.land_mask)
    leading = ", ".join(
        f"{BIOMES[key][0].lower()} ({share:.0%})" for key, share in biomes[:3]
    )
    peak = world.highest()

    add(
        f"{world.name} is {shape_prose} between {lat_lo:.0f}° and {lat_hi:.0f}° of "
        f"latitude, {world.width * world.cell_km:,.0f} km across. "
        f"Its {world.land_cell_count() * world.cell_km ** 2:,.0f} km² of land carry "
        f"{world.coast_km():,.0f} km of coastline. The prevailing wind comes from "
        f"the {climate.wind}, so rain falls on the {climate.wind}ward slopes and "
        f"the far side of every range lies in its shadow. The ground is mostly "
        f"{leading}. The highest point stands {world.metres(peak):,.0f} m above the "
        f"sea, in the {_cell_bearing(world, peak)} quarter."
    )
    add("")

    tongues = world.namer.languages
    if len(tongues) == 1:
        add("Every name on this sheet comes from a single tongue:")
    else:
        add(
            f"Names on this sheet come from {len(tongues)} tongues, each holding "
            f"the ground nearest its own centre:"
        )
    add("")
    for language in tongues:
        add(f"- **{language.name}** — {language.blurb}")
    add("")

    if features.regions:
        add("## Regions")
        add("")
        add("| Region | Predominant cover | Area |")
        add("|---|---|---|")
        for region in sorted(features.regions, key=lambda r: -r.area_km2):
            add(
                f"| {region.name} | {BIOMES[region.biome][0].lower()} "
                f"| {region.area_km2:,.0f} km² |"
            )
        add("")

    if features.rivers:
        add("## Rivers")
        add("")
        add("| River | Length | Order | Mouth |")
        add("|---|---|---|---|")
        for river in sorted(features.rivers, key=lambda r: -r.length_km):
            add(
                f"| {river.name} | {river.length_km:,.0f} km | {river.order} "
                f"| {_cell_bearing(world, river.mouth)} coast |"
            )
        add("")
        add(
            "*Order is the Strahler number: two streams of equal order meet to "
            "make one of the next order up. Nothing here was drawn — every "
            "watercourse is a line of cells that accumulated more than "
            f"{world.hydro.channel_area:,.0f} cells' worth of drainage.*"
        )
        add("")

    if features.ranges:
        add("## Highlands")
        add("")
        add("| Range | Highest point | Extent |")
        add("|---|---|---|")
        summit_by_index = {s.index: s for s in features.summits}
        for mountains in sorted(features.ranges, key=lambda r: -r.peak_m):
            summit = summit_by_index.get(mountains.peak)
            peak_name = f"{summit.name}, " if summit else ""
            add(
                f"| {mountains.name} | {peak_name}{mountains.peak_m:,.0f} m "
                f"| {mountains.area_km2:,.0f} km² |"
            )
        add("")

    if features.lakes:
        add("## Lakes")
        add("")
        for lake in sorted(features.lakes, key=lambda l: -l.area_km2):
            add(
                f"- **{lake.name}** — {lake.area_km2:,.0f} km², "
                f"{_bearing(world, *lake.centroid)} interior"
            )
        add("")

    if features.islands:
        add("## Islands")
        add("")
        for island in sorted(features.islands, key=lambda i: -i.area_km2):
            add(
                f"- **{island.name}** — {island.area_km2:,.0f} km², "
                f"off the {_bearing(world, *island.centroid)} shore"
            )
        add("")

    if features.waters or features.capes:
        add("## Waters and headlands")
        add("")
        for water in features.waters:
            where = _cell_bearing(world, water.index)
            if water.area_km2:
                add(f"- **{water.name}** ({water.kind}) — {water.area_km2:,.0f} km², {where}")
            else:
                add(f"- **{water.name}** ({water.kind}) — {where} coast")
        for cape in features.capes:
            add(f"- **{cape.name}** (cape) — {_cell_bearing(world, cape.index)} coast")
        add("")

    add("## How this sheet was made")
    add("")
    add(
        "Fractal noise raised a landmass and set two or three mountain belts "
        "along the zero-contours of a smooth field. Stream-power erosion then "
        f"ran for a number of steps, each one routing water over the whole grid "
        f"and cutting in proportion to how much passed and how steeply it fell. "
        f"The drainage network, the {len(features.rivers)} named "
        f"{plural(len(features.rivers), 'river')}, the lakes and the shape of "
        f"every valley are consequences of that, not decisions. Rain was swept "
        f"across the map from the {climate.wind} and dropped where the ground "
        f"rose. Biomes follow from the rain and the latitude. The names came "
        f"last, because what you call a place depends on what it turned out to be."
    )
    add("")
    add(f"Reproduce this world exactly with `silt {world.seed}`.")
    add("")
    return "\n".join(lines)


